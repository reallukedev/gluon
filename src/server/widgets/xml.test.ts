import { describe, expect, it } from "vitest";
import { type XmlNode, child, children, decodeEntities, htmlToText, parseXml, textOf } from "./xml";

const names = (n: XmlNode | undefined) => (n?.children ?? []).map((c) => c.name);

describe("decodeEntities", () => {
  it("returns strings without & untouched", () => {
    const s = "plain text < no entities > here";
    expect(decodeEntities(s)).toBe(s);
    expect(decodeEntities(s, true)).toBe(s);
  });

  it.each([false, true])("decodes XML, numeric and common HTML entities (html=%s)", (html) => {
    expect(decodeEntities("&lt;a&gt; &amp; &quot;b&quot; &apos;c&apos;", html)).toBe(`<a> & "b" 'c'`);
    expect(decodeEntities("&#65;&#x41;&#X41;&#x1F600;", html)).toBe("AAA😀");
    expect(decodeEntities("a&nbsp;b&hellip;&mdash;&rsquo;&eacute;&copy;&euro;co&shy;op", html)).toBe("a\u00a0b\u2026\u2014\u2019\u00e9\u00a9\u20accoop");
  });

  it.each(["&#0;", "&#xD800;", "&#xDFFF;", "&#x110000;", "&#55296;"])("drops invalid code point %s", (ref) => {
    expect(decodeEntities(`x${ref}y`)).toBe("xy");
  });

  it("leaves unknown names, bare ampersands and wrong-case names alone", () => {
    expect(decodeEntities("&bogus; AT&T R&D &AMP; &Auml;&auml;")).toBe("&bogus; AT&T R&D &AMP; Ää");
  });

  it("does not double-decode", () => {
    expect(decodeEntities("&amp;lt;")).toBe("&lt;");
  });
});

describe("parseXml", () => {
  it("builds a tree of a small RSS feed with attributes, CDATA, comments and PIs", () => {
    const src = `<?xml version="1.0" encoding="utf-8"?>
<!-- generated by example.com -->
<rss version="2.0" xmlns:dc='http://purl.org/dc/elements/1.1/'>
  <channel>
    <title><![CDATA[<b>Hi</b> &amp;]]></title>
    <link href='https://example.com/a?x=1&amp;y=2' rel=alternate hidden/>
    <item><dc:title>Caf&eacute; news &amp; more</dc:title><guid isPermaLink="false">abc-1</guid></item>
    <item><title>Second</title></item>
  </channel>
</rss>`;
    const doc = parseXml(src);
    expect(doc.name).toBe("#document");
    expect(names(doc)).toEqual(["rss"]);
    const rss = doc.children[0];
    expect(rss.attrs).toEqual({
      version: "2.0",
      "xmlns:dc": "http://purl.org/dc/elements/1.1/",
    });
    const channel = child(rss, "channel")!;
    expect(names(channel)).toEqual(["title", "link", "item", "item"]);
    expect(child(channel, "title")!.text).toBe("<b>Hi</b> &amp;");
    expect(child(channel, "link")).toMatchObject({
      attrs: {
        href: "https://example.com/a?x=1&y=2",
        rel: "alternate",
        hidden: "",
      },
      children: [],
    });
    const items = children(channel, "item", "entry");
    expect(items).toHaveLength(2);
    expect(child(items[0], "title", "dc:title")!.text).toBe("Café news & more");
    expect(child(items[0], "guid")!.attrs.isPermaLink).toBe("false");
    expect(child(items[1], "title", "dc:title")!.text).toBe("Second");
  });

  it("keeps whitespace in text and does not let self-closing tags capture text", () => {
    const doc = parseXml("<p>  a <br/> b  </p><hr/>tail");
    const p = doc.children[0];
    expect(p.text).toBe("  a  b  ");
    expect(child(p, "br")!.text).toBe("");
    expect(doc.text).toContain("tail");
  });

  it("never expands entities declared in a DOCTYPE", () => {
    const doc = parseXml('<!DOCTYPE x [<!ENTITY e "boom">]><t>&e;</t>');
    expect(names(doc)).toEqual(["t"]);
    expect(doc.children[0].text).toBe("&e;");
  });

  it("returns promptly on a billion laughs document without expanding it", () => {
    const decls = ['<!ENTITY lol "lol">'];
    for (let i = 1; i <= 9; i++) decls.push(`<!ENTITY lol${i} "${`&lol${i === 1 ? "" : i - 1};`.repeat(10)}">`);
    const src = `<?xml version="1.0"?><!DOCTYPE lolz [${decls.join("")}]><lolz>&lol9;</lolz>`;
    const started = performance.now();
    const doc = parseXml(src);
    expect(performance.now() - started).toBeLessThan(500);
    expect(doc.children[0].text).toBe("&lol9;");
  });

  it("does not fetch or read an external entity", () => {
    const doc = parseXml('<!DOCTYPE foo [<!ENTITY xxe SYSTEM "file:///etc/passwd">]><foo>&xxe;</foo>');
    expect(doc.children[0].text).toBe("&xxe;");
  });

  it("recovers from mismatched and unclosed tags", () => {
    const doc = parseXml("<item><title>Unclosed<item2>t</item>");
    const item = doc.children[0];
    expect(names(item)).toEqual(["title"]);
    const title = item.children[0];
    expect(title.text).toBe("Unclosed");
    expect(names(title)).toEqual(["item2"]);
    expect(title.children[0].text).toBe("t");

    const stray = parseXml("<a>x</b>y</a><c/>");
    expect(names(stray)).toEqual(["a", "c"]);
    expect(stray.children[0].text).toBe("xy");
  });

  it("keeps a < that doesn't start a tag as text", () => {
    expect(parseXml("<p>1 < 2 and 3 > 2</p>").children[0].text).toBe("1 < 2 and 3 > 2");
    expect(parseXml("<q><></q>").children[0].text).toBe("<>");
  });

  it.each([
    ["comment", "<a>x<!-- never closed"],
    ["CDATA", "<a>x<![CDATA[ never closed"],
    ["PI", "<a>x<?php echo 1"],
    ["DOCTYPE", "<!DOCTYPE html [ <!ENTITY"],
    ["tag", '<a href="x'],
  ])("consumes an unterminated %s without throwing", (_, src) => {
    expect(() => parseXml(src)).not.toThrow();
  });

  it("stops creating elements after maxNodes", () => {
    const doc = parseXml("<r><i>1</i><i>2</i><i>3</i><i>4</i></r>", {
      maxNodes: 3,
      maxDepth: 64,
    });
    expect(children(doc.children[0], "i").map((i) => i.text)).toEqual(["1", "2"]);
  });

  it("flattens elements below maxDepth into the deepest open ancestor", () => {
    const doc = parseXml("<a><b><c>x</c></b></a>", {
      maxDepth: 2,
      maxNodes: 100,
    });
    const a = doc.children[0];
    expect(names(a)).toEqual(["b", "c"]);
    expect(a.text).toBe("x");
  });

  it("caps the default depth on a deeply nested document", () => {
    const depth = 5000;
    const doc = parseXml(`${"<d>".repeat(depth)}deep${"</d>".repeat(depth)}`);
    let n: XmlNode | undefined = doc;
    let levels = 0;
    while (n && n.children.length) {
      n = n.children[0];
      levels++;
    }
    expect(levels).toBeLessThanOrEqual(65);
  });

  it("never throws on random or truncated input", () => {
    let seed = 1234567;
    const rand = () => {
      seed = (seed * 1103515245 + 12345) % 2 ** 31;
      return seed / 2 ** 31;
    };
    const alphabet = [
      "<",
      ">",
      "/",
      "!",
      "?",
      "[",
      "]",
      "-",
      "&",
      ";",
      "#",
      "x",
      "a",
      "=",
      '"',
      "'",
      " ",
      "CDATA",
      "DOCTYPE",
      "é",
    ];
    const sample = `<?xml version="1.0"?><feed><entry a="1"><title type='html'>&lt;b&gt;</title><![CDATA[z]]></entry></feed>`;
    for (let i = 0; i < 500; i++) {
      const len = Math.floor(rand() * 80);
      let s = "";
      for (let j = 0; j < len; j++) s += alphabet[Math.floor(rand() * alphabet.length)];
      expect(() => parseXml(s)).not.toThrow();
      expect(() => parseXml(sample.slice(0, Math.floor(rand() * sample.length)))).not.toThrow();
    }
  });
});

describe("helpers", () => {
  const doc = parseXml("<entry>Intro <b>bold <i>it</i></b> end<title>T</title></entry>");
  const entry = doc.children[0];

  it("finds children by any of several names", () => {
    expect(child(entry, "nope", "title")?.text).toBe("T");
    expect(child(entry, "nope")).toBeUndefined();
    expect(child(undefined, "title")).toBeUndefined();
    expect(children(entry, "b", "title").map((c) => c.name)).toEqual(["b", "title"]);
    expect(children(undefined, "x")).toEqual([]);
  });

  it("joins own text and then each child's text depth-first", () => {
    expect(textOf(child(entry, "title"))).toBe("T");
    expect(textOf(child(entry, "b"))).toBe("bold it");
    expect(textOf(entry)).toBe("Intro  end" + "bold it" + "T");
    expect(textOf(undefined)).toBe("");
  });
});

describe("htmlToText", () => {
  it("strips blocks and tags, decodes HTML entities and collapses whitespace", () => {
    expect(htmlToText("<style>p{}</style><p>One</p><p>Two&hellip;   three</p><br>four")).toBe("One Two… three four");
    expect(
      htmlToText(
        '<script>alert("x")</script><noscript>Enable JS</noscript><iframe src="https://example.com"></iframe><h2>Title</h2><ul><li>a</li><li>b</li></ul><div>c&nbsp;d</div>',
      ),
    ).toMatch(/^Title a b c\s?d$/);
  });

  it("cuts long text at a word boundary with an ellipsis", () => {
    expect(htmlToText("<p>Hello&nbsp;<b>world</b></p>", 8)).toBe("Hello…");
    expect(htmlToText("abcdefghij", 5)).toBe("abcd…");
    expect(htmlToText("short", 5)).toBe("short");
  });

  it("keeps every result within max", () => {
    const text = "Lorem ipsum dolor sit amet, consectetur adipiscing elit. ".repeat(20);
    expect(htmlToText(text).length).toBeLessThanOrEqual(280);
    expect(htmlToText(text).endsWith("…")).toBe(true);
    for (let max = 2; max < 60; max++) expect(htmlToText(text, max).length).toBeLessThanOrEqual(max);
  });
});
