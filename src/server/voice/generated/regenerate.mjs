// Rebuilds MumbleServer.js and MumbleServer.d.ts from MumbleServer.ice (Mumble 1.5's admin API,
// from mumble-voip/mumble src/murmur/MumbleServer.ice at the matching v1.5.x tag).
//
//   node src/server/voice/generated/regenerate.mjs
//
// slice2js (a dev dependency) writes a browser/Node wrapper that passes `require` around as a
// value, which bundlers can't follow. This rewrites it as a plain ES module that imports "ice"
// and defines the types once per process.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, "../../../../node_modules/slice2js");
const plat = { darwin: "macos-arm64", linux: os.arch() === "arm64" ? "linux-arm64" : "linux-x64", win32: "windows-x64" }[os.platform()];
const exe = path.join(pkg, "bin", plat, os.platform() === "win32" ? "slice2js.exe" : "slice2js");
const out = fs.mkdtempSync(path.join(os.tmpdir(), "slice2js-"));
execFileSync(exe, [`-I${path.join(pkg, "slice")}`, "--typescript", "--output-dir", out, path.join(here, "MumbleServer.ice")], { stdio: "inherit" });

const header = `// Generated by slice2js from MumbleServer.ice. Don't edit: run node src/server/voice/generated/regenerate.mjs\n`;
const js = fs.readFileSync(path.join(out, "MumbleServer.js"), "utf8");
const start = js.indexOf('const Ice = require("ice").Ice;');
const end = js.lastIndexOf("exports.MumbleServer = MumbleServer;");
if (start < 0 || end < 0) throw new Error("slice2js output changed shape; update regenerate.mjs");
const body = js.slice(start + 'const Ice = require("ice").Ice;'.length, end);
// Every server bundle that imports this runs it, but Ice's type registry is one per process and
// refuses a second definition, so later copies reuse the first one's module.
const wrapped = `const MumbleServer = (() => {\n    const existing = Ice._ModuleRegistry.module("MumbleServer");\n    if (existing.MetaPrx) return existing;\n${body}\n    return MumbleServer;\n})();\n`;
fs.writeFileSync(path.join(here, "MumbleServer.js"), `${header}/* eslint-disable */\nimport { Ice } from "ice";\n\n${wrapped}\nexport { MumbleServer };\n`);

const dts = fs.readFileSync(path.join(out, "MumbleServer.d.ts"), "utf8").replace(/^[\s\S]*?(import \* as iceNS0 from "ice")/, `${header}$1`);
fs.writeFileSync(path.join(here, "MumbleServer.d.ts"), dts);
fs.rmSync(out, { recursive: true, force: true });
console.log("Wrote MumbleServer.js and MumbleServer.d.ts");
